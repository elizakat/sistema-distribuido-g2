    private void cargarTipoMovimiento() {

    try {

        TipoMovimientoDAO dao =
                new TipoMovimientoDAO();

        List<TipoMovimiento> lista =
                dao.listar();

        System.out.println(
                "Cantidad registros: "
                + lista.size()
        );

        DefaultTableModel modelo =
                new DefaultTableModel();

        modelo.addColumn("ID");
        modelo.addColumn("DESCRIPCION");
        modelo.addColumn("SIGNO");

        for (TipoMovimiento tipo : lista) {

            modelo.addRow(
                    new Object[]{
                        tipo.getIdTipoMovimiento(),
                        tipo.getDescripcion(),
                        tipo.getSigno()
                    }
            );
        }

        tblTipoMovimiento.setModel(modelo);

    } catch (Exception ex) {

        ex.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                ex.toString()
        );
    }
}
