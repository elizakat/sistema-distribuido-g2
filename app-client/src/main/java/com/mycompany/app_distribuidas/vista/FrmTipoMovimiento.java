    private void tblTipoMovimientoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblTipoMovimientoMouseClicked
        int fila =
        tblTipoMovimiento.getSelectedRow();

if (fila >= 0) {

    txtIdTipoMovimiento.setText(
            tblTipoMovimiento.getValueAt(
                    fila,
                    0
            ).toString()
    );

    txtDescripcion.setText(
            tblTipoMovimiento.getValueAt(
                    fila,
                    1
            ).toString()
    );

    String signo =
            tblTipoMovimiento.getValueAt(
                    fila,
                    2
            ).toString();

    if (signo.equals("1")) {

        cmbSigno.setSelectedIndex(0);

    } else {

        cmbSigno.setSelectedIndex(1);
    }
}
    }//GEN-LAST:event_tblTipoMovimientoMouseClicked

