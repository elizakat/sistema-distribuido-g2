    private void cargarUsuarios() {

    UsuarioDAO dao =
            new UsuarioDAO();

    List<Usuario>lista =
            dao.listarUsuarios();

    DefaultTableModel modelo =
            new DefaultTableModel();

    modelo.addColumn("ID");
    modelo.addColumn("Usuario");
    modelo.addColumn("Clave");
    modelo.addColumn("Estado");
    modelo.addColumn("Tipo Usuario");

    for (Usuario u : lista) {

        modelo.addRow(
                new Object[]{
                    u.getIdUsuario(),
                    u.getUsername(),
                    "******",
                    u.getEstado(),
                    u.getTipoUsuario()
                }
        );
    }

    tblUsuarios.setModel(modelo);
}
