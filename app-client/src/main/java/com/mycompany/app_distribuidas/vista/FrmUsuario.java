    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        Usuario usuario = new Usuario();

usuario.setUsername(
        txtUsuario.getText()
);

usuario.setClave(
        txtClave.getText()
);

String estado =
        cmbEstado.getSelectedItem()
        .toString();

if (estado.startsWith("A")) {

    usuario.setEstado("A");

} else {

    usuario.setEstado("I");
}

String tipoUsuario =
        cmbTipoUsuario.getSelectedItem()
                .toString();

if (tipoUsuario.startsWith("A")) {

    usuario.setTipoUsuario("A");

} else {

    usuario.setTipoUsuario("U");
}




UsuarioDAO dao =
        new UsuarioDAO();
if (dao.existeUsuario(
        txtUsuario.getText()
)) {

    JOptionPane.showMessageDialog(
            this,
            "El usuario ya existe"
    );

    return;
}
boolean guardado =
        dao.guardarUsuario(usuario);

if (guardado) {

    JOptionPane.showMessageDialog(
            this,
            "Usuario guardado correctamente"
    );

    cargarUsuarios();
    limpiarCampos();
} else {

    JOptionPane.showMessageDialog(
            this,
            "Error al guardar usuario"
    );
}

    }//GEN-LAST:event_btnGuardarActionPerformed

    private void tblUsuariosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUsuariosMouseClicked
        int fila = tblUsuarios.getSelectedRow();

if (fila >= 0) {

    txtIdUsuario.setText(
            tblUsuarios.getValueAt(
                    fila, 0
            ).toString()
    );

    txtUsuario.setText(
            tblUsuarios.getValueAt(
                    fila, 1
            ).toString()
    );

    
    String estado =
            tblUsuarios.getValueAt(
                    fila, 3
            ).toString();

    if (estado.equals("A")) {

        cmbEstado.setSelectedIndex(0);

    } else {

        cmbEstado.setSelectedIndex(1);
    }
}
 String tipoUsuario =
        tblUsuarios.getValueAt(
                fila, 4
        ).toString();

if (tipoUsuario.equals("A")) {

    cmbTipoUsuario.setSelectedIndex(0);

} else {

    cmbTipoUsuario.setSelectedIndex(1);
}       
    }//GEN-LAST:event_tblUsuariosMouseClicked

