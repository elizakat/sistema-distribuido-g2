    private void btnAgregarDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarDetalleActionPerformed
      
if (txtCantidad.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese la cantidad"
        );

        return;
    }

    if (txtPrecio.getText().trim().isEmpty()) {

        JOptionPane.showMessageDialog(
                this,
                "Ingrese el precio"
        );

        return;
    }

    DefaultTableModel modelo =
            (DefaultTableModel)
            tblDetalleMovimiento.getModel();

    double cantidad =
            Double.parseDouble(
                    txtCantidad.getText()
            );

    double precio =
            Double.parseDouble(
                    txtPrecio.getText()
            );

    double subtotal =
            cantidad * precio;

    modelo.addRow(
            new Object[]{
                0,
                cmbArticulo.getSelectedItem(),
                cantidad,
                precio,
                subtotal
                
            }
            
    );
    calcularTotal();
    txtCantidad.setText("");
    txtPrecio.setText("");

    

    }//GEN-LAST:event_btnAgregarDetalleActionPerformed

    private void btnEliminarDetalleActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarDetalleActionPerformed
        int fila =
            tblDetalleMovimiento
            .getSelectedRow();

    if (fila >= 0) {

        DefaultTableModel modelo =
                (DefaultTableModel)
                tblDetalleMovimiento
                .getModel();

        modelo.removeRow(fila);
        calcularTotal();
    }
    }
private void calcularTotal() {

    double total = 0;

    DefaultTableModel modelo =
            (DefaultTableModel)
            tblDetalleMovimiento.getModel();

    for (int i = 0;
         i < modelo.getRowCount();
         i++) {

        total += Double.parseDouble(
                modelo.getValueAt(
                        i,
                        4
                ).toString()
        );
    }

    System.out.println(
            "TOTAL: " + total
    );

    }//GEN-LAST:event_btnEliminarDetalleActionPerformed

