    private void btnGuardarMovimientoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarMovimientoActionPerformed
  try {

        JsonObject movimiento =
        new JsonObject();

movimiento.addProperty(
        "fecha",
        txtFecha.getText()
);

movimiento.addProperty(
        "idTipoMovimiento",
        cmbTipoMovimiento.getSelectedIndex() + 1
);

movimiento.addProperty(
        "observacion",
        txtObservacion.getText()
);
JsonArray detalles =
        new JsonArray();

DefaultTableModel modelo =
        (DefaultTableModel)
        tblDetalleMovimiento.getModel();

for (int i = 0;
     i < modelo.getRowCount();
     i++) {

    JsonObject detalle =
            new JsonObject();

    detalle.addProperty(
            "idArticulo",
            1
    );

    detalle.addProperty(
            "cantidad",
            Double.parseDouble(
                    modelo.getValueAt(
                            i,
                            2
                    ).toString()
            )
    );

    detalle.addProperty(
            "precio",
            Double.parseDouble(
                    modelo.getValueAt(
                            i,
                            3
                    ).toString()
            )
    );

    detalles.add(detalle);
}

movimiento.add(
        "detalles",
        detalles
);

        MovimientoInventarioDAO dao =
                new MovimientoInventarioDAO();

        boolean guardado =
                dao.guardarMovimiento(
                        movimiento
                );

        JOptionPane.showMessageDialog(
                this,
                "Resultado: "
                + guardado
        );

    } catch (Exception ex) {

        ex.printStackTrace();

        JOptionPane.showMessageDialog(
                this,
                ex.toString()
        );
    }
  
    }//GEN-LAST:event_btnGuardarMovimientoActionPerformed

