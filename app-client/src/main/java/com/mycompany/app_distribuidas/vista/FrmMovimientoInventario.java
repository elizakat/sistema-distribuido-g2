private void cargarComboArticulos() {

    ArticuloDAO dao =
            new ArticuloDAO();

    List<Articulo> lista =
            dao.listarArticulos();

    cmbArticulo.removeAllItems();

    for (Articulo articulo : lista) {

        cmbArticulo.addItem(
                articulo.getNombre()
        );
    }
}
private void cargarComboTipoMovimiento() {

    TipoMovimientoDAO dao =
            new TipoMovimientoDAO();

    List<TipoMovimiento> lista =
            dao.listar();

    cmbTipoMovimiento.removeAllItems();

    for (TipoMovimiento tipo : lista) {

        cmbTipoMovimiento.addItem(
                tipo.getDescripcion()
        );
    }
    
}
