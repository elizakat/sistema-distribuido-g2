CREATE TABLE USUARIO (
    ID_USUARIO NUMBER(10) NOT NULL,
    USERNAME VARCHAR2(50) NOT NULL,
    CLAVE VARCHAR2(255) NOT NULL,
    ESTADO CHAR(1) DEFAULT 'A' NOT NULL,
    TIPO_USUARIO CHAR(1) DEFAULT 'U' NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_USERNAME UNIQUE (USERNAME),
    CONSTRAINT CK_USUARIO_ESTADO CHECK (ESTADO IN ('A','I')),
    CONSTRAINT CK_USUARIO_TIPO CHECK (TIPO_USUARIO IN ('A','U'))
);

CREATE TABLE ARTICULO (
    ID_ARTICULO NUMBER(10) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRECIO NUMBER(12,2) DEFAULT 0 NOT NULL,
    STOCK_ACTUAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_ARTICULO PRIMARY KEY (ID_ARTICULO),
    CONSTRAINT CK_ART_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_ART_STOCK CHECK (STOCK_ACTUAL >= 0)
);

CREATE TABLE TIPO_MOVIMIENTO (
    ID_TIPO_MOV NUMBER(10) NOT NULL,
    DESCRIPCION VARCHAR2(50) NOT NULL,
    SIGNO NUMBER(1) NOT NULL,
    CONSTRAINT PK_TIPO_MOVIMIENTO PRIMARY KEY (ID_TIPO_MOV),
    CONSTRAINT CK_TIP_MOV_SIGNO CHECK (SIGNO IN (1,-1))
);

CREATE TABLE MOVIMIENTO_INVENTARIO (
    ID_MOVIMIENTO NUMBER(10) NOT NULL,
    ID_TIPO_MOV NUMBER(10) NOT NULL,
    FECHA DATE DEFAULT SYSDATE NOT NULL,
    OBSERVACION VARCHAR2(200),
    CONSTRAINT PK_MOVIMIENTO_INVENTARIO PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT FK_MOV_TIPO FOREIGN KEY (ID_TIPO_MOV) REFERENCES TIPO_MOVIMIENTO (ID_TIPO_MOV)
);

CREATE TABLE DETALLE_MOVIMIENTO (
    ID_DETALLE_MOV NUMBER(10) NOT NULL,
    ID_ARTICULO NUMBER(10) NOT NULL,
    ID_MOVIMIENTO NUMBER(10) NOT NULL,
    CANTIDAD NUMBER(12,2) NOT NULL,
    PRECIO NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_DETALLE_MOVIMIENTO PRIMARY KEY (ID_DETALLE_MOV),
    CONSTRAINT FK_DETM_ART FOREIGN KEY (ID_ARTICULO) REFERENCES ARTICULO (ID_ARTICULO),
    CONSTRAINT FK_DETM_MOV FOREIGN KEY (ID_MOVIMIENTO) REFERENCES MOVIMIENTO_INVENTARIO (ID_MOVIMIENTO),
    CONSTRAINT CK_DETM_CANT CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETM_PRECIO CHECK (PRECIO >= 0)
);

CREATE TABLE CLIENTE (
    ID_CLIENTE NUMBER(10) NOT NULL,
    RUC VARCHAR2(20) NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    DIRECCION VARCHAR2(150),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
    CONSTRAINT UQ_CLIENTE_RUC UNIQUE (RUC)
);

CREATE TABLE CIUDAD_ENTREGA (
    ID_CIUDAD NUMBER(10) NOT NULL,
    NOMBRE_CIUDAD VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_CIUDAD_ENTREGA PRIMARY KEY (ID_CIUDAD),
    CONSTRAINT UQ_CIUDAD_NOMBRE UNIQUE (NOMBRE_CIUDAD)
);

CREATE TABLE FACTURA (
    ID_FACTURA NUMBER(10) NOT NULL,
    ID_CLIENTE NUMBER(10) NOT NULL,
    ID_CIUDAD NUMBER(10) NOT NULL,
    NUMERO_FACTURA VARCHAR2(20) NOT NULL,
    FECHA_EMISION DATE DEFAULT SYSDATE NOT NULL,
    SUBTOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    IMPUESTO NUMBER(12,2) DEFAULT 0 NOT NULL,
    TOTAL NUMBER(12,2) DEFAULT 0 NOT NULL,
    ESTADO VARCHAR2(12) DEFAULT 'BORRADOR' NOT NULL,
    CONSTRAINT PK_FACTURA PRIMARY KEY (ID_FACTURA),
    CONSTRAINT UQ_FACTURA_NUMERO UNIQUE (NUMERO_FACTURA),
    CONSTRAINT FK_FACTURA_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE (ID_CLIENTE),
    CONSTRAINT FK_FACTURA_CIUDAD FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD_ENTREGA (ID_CIUDAD),
    CONSTRAINT CK_FACTURA_MONTOS CHECK (SUBTOTAL >= 0 AND IMPUESTO >= 0 AND TOTAL >= 0),
    CONSTRAINT CK_FACTURA_ESTADO CHECK (ESTADO IN ('BORRADOR','CONFIRMADA','ANULADA'))
);

CREATE TABLE DETALLE_FACTURA (
    ID_DETALLE_FAC NUMBER(10) NOT NULL,
    ID_FACTURA NUMBER(10) NOT NULL,
    ID_ARTICULO NUMBER(10) NOT NULL,
    CANTIDAD NUMBER(12,2) NOT NULL,
    PRECIO_VENTA NUMBER(12,2) NOT NULL,
    CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY (ID_DETALLE_FAC),
    CONSTRAINT FK_DETF_FACT FOREIGN KEY (ID_FACTURA) REFERENCES FACTURA (ID_FACTURA),
    CONSTRAINT FK_DETF_ART FOREIGN KEY (ID_ARTICULO) REFERENCES ARTICULO (ID_ARTICULO),
    CONSTRAINT CK_DETF_CANT CHECK (CANTIDAD > 0),
    CONSTRAINT CK_DETF_PRECIO CHECK (PRECIO_VENTA >= 0)
);

CREATE TABLE FACTURA_MOVIMIENTO (
    ID_FACTURA NUMBER(10) NOT NULL,
    ID_MOVIMIENTO NUMBER(10) NOT NULL,
    ID_MOVIMIENTO_REVERSA NUMBER(10),
    CONSTRAINT PK_FACTURA_MOVIMIENTO PRIMARY KEY (ID_FACTURA),
    CONSTRAINT UQ_FM_MOV UNIQUE (ID_MOVIMIENTO),
    CONSTRAINT FK_FM_FACTURA FOREIGN KEY (ID_FACTURA) REFERENCES FACTURA (ID_FACTURA),
    CONSTRAINT FK_FM_MOV FOREIGN KEY (ID_MOVIMIENTO) REFERENCES MOVIMIENTO_INVENTARIO (ID_MOVIMIENTO),
