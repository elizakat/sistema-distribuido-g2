-- CxC parcial: los cobros reducen saldo de facturas; sin pantalla CxC.
CREATE OR REPLACE VIEW V_SALDO_FACTURA AS
SELECT f.ID_FACTURA, f.NUMERO_FACTURA, f.FECHA_EMISION, f.ID_CLIENTE, f.TOTAL, f.ESTADO,
       NVL(p.PAGADO,0) AS TOTAL_PAGADO,
       CASE WHEN f.ESTADO <> 'CONFIRMADA' THEN 0 ELSE f.TOTAL - NVL(p.PAGADO,0) END AS SALDO_PENDIENTE
FROM FACTURA f
LEFT JOIN (SELECT ID_FACTURA, SUM(MONTO_APLICADO) AS PAGADO FROM DETALLE_COBRO GROUP BY ID_FACTURA) p
  ON p.ID_FACTURA = f.ID_FACTURA;

